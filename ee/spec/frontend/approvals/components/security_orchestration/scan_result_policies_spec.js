import Vue from 'vue';
import VueApollo from 'vue-apollo';
import { GlButton } from '@gitlab/ui';
import { mount } from '@vue/test-utils';
import createMockApollo from 'helpers/mock_apollo_helper';
import waitForPromises from 'helpers/wait_for_promises';
import CrudComponent from '~/vue_shared/components/crud_component.vue';
import ScanResultPolicies from 'ee/approvals/components/security_orchestration/scan_result_policies.vue';
import ScanResultPolicy from 'ee/approvals/components/security_orchestration/scan_result_policy.vue';
import PolicyDetails from 'ee/approvals/components/security_orchestration/policy_details.vue';
import projectSecurityPoliciesQuery from 'ee/security_orchestration/graphql/queries/project_security_policies.query.graphql';
import {
  mockProjectScanResultPolicyList,
  mockDefaultBranchesScanResultManifest,
} from 'ee_jest/security_orchestration/mocks/mock_scan_result_policy_data';
import {
  projectSecurityPolicies,
  defaultPageInfo,
} from 'ee_jest/security_orchestration/mocks/mock_apollo';
import { APPROVAL_POLICY_FILTER_TYPE } from 'ee/security_orchestration/components/policies/constants';

Vue.use(VueApollo);

// Create a modified yaml for the second policy with a different name
const mockSecondPolicyYaml = mockDefaultBranchesScanResultManifest.replace(
  'name: critical vulnerability CS approvals',
  'name: low vulnerability SAST approvals',
);

// Second mock policy with branches
const mockSecondPolicy = {
  ...mockProjectScanResultPolicyList,
  id: 'gid://gitlab/Security::ApprovalPolicy/2',
  name: 'low vulnerability SAST approvals',
  yaml: mockSecondPolicyYaml,
  enabled: true,
};

const emptyPoliciesResponse = {
  data: {
    namespace: {
      id: '1',
      securityPolicies: {
        nodes: [],
        pageInfo: defaultPageInfo,
      },
    },
  },
};

const NO_SECURITY_POLICIES_MESSAGE = "You don't have any security policies yet";

describe('ScanResultPolicies', () => {
  let wrapper;
  let queryHandler;

  const createMockApolloProvider = (handler) => {
    queryHandler = handler;
    return createMockApollo([[projectSecurityPoliciesQuery, handler]]);
  };

  const defaultPoliciesHandler = projectSecurityPolicies([
    mockProjectScanResultPolicyList,
    mockSecondPolicy,
  ]);

  const factory = (handler = defaultPoliciesHandler) => {
    wrapper = mount(ScanResultPolicies, {
      provide: {
        fullPath: 'full/path',
        newPolicyPath: 'policy/new',
      },
      apolloProvider: createMockApolloProvider(handler),
    });
  };

  const findAllScanResultPolicies = () => wrapper.findAllComponents(ScanResultPolicy);
  const findAllPolicyDetails = () => wrapper.findAllComponents(PolicyDetails);
  const findCrudComponent = () => wrapper.findComponent(CrudComponent);

  it('passes correct props to CRUD component', async () => {
    factory();
    await waitForPromises();

    expect(findCrudComponent().props('title')).toBe('Security Approvals');
    expect(findCrudComponent().props('icon')).toBe('shield');
    expect(findCrudComponent().text()).toContain(
      'Create security policies to enforce security and compliance controls that help keep your project secure.',
    );
  });

  it('calls the GraphQL query with correct variables', async () => {
    factory();
    await waitForPromises();

    expect(queryHandler).toHaveBeenCalledWith(
      expect.objectContaining({
        fullPath: 'full/path',
        type: APPROVAL_POLICY_FILTER_TYPE,
      }),
    );
  });

  describe('when no policy is available', () => {
    beforeEach(async () => {
      factory(jest.fn().mockResolvedValue(emptyPoliciesResponse));
      await waitForPromises();
    });

    it('renders message for the empty state', () => {
      expect(wrapper.text()).toContain(NO_SECURITY_POLICIES_MESSAGE);
    });

    it('shows zero count', () => {
      expect(findCrudComponent().props('count')).toEqual(0);
    });
  });

  describe('when there are policies available', () => {
    beforeEach(async () => {
      factory();
      await waitForPromises();
    });

    it('renders components related to each policy', () => {
      expect(wrapper.text()).not.toContain(NO_SECURITY_POLICIES_MESSAGE);
      expect(findAllScanResultPolicies()).toHaveLength(2);
      expect(findAllPolicyDetails()).toHaveLength(2);
    });

    it('shows correct count', () => {
      expect(findCrudComponent().props('count')).toEqual(2);
    });

    describe('when toggle event is generated by the scan result policy', () => {
      it('updates isSelected to the respective policy', async () => {
        expect(findAllScanResultPolicies().at(0).props('policy').isSelected).toBe(false);

        const scanResultButton = findAllScanResultPolicies().at(0).findComponent(GlButton);
        await scanResultButton.trigger('click');

        expect(findAllScanResultPolicies().at(0).props('policy').isSelected).toBe(true);
      });
    });
  });

  describe('when it fails to fetch policies', () => {
    beforeEach(async () => {
      factory(jest.fn().mockRejectedValue(new Error('GraphQL error')));
      await waitForPromises();
    });

    it('renders message for the empty state', () => {
      expect(wrapper.text()).toContain(NO_SECURITY_POLICIES_MESSAGE);
    });
  });
});
